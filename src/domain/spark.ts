/**
 * 火花记号（logo / 品牌图形）的几何。
 *
 * ---- 为什么要换掉原来那个记号 ----
 *
 * 换成「一朵小火花」有两条硬理由，都不是「换个样子」：
 *
 *   1. **旧图标画的是一团火，新的是一个火花。** 旧的 `icon.png` 是一个发光的
 *      蓝色「Λ」形（一个箭头，语义上是「上升」而不是「火」），底栏「今天」
 *      那个图标则是一簇火苗。而 App 的名字 Ember 的意思是**余烬**——火快灭
 *      但还亮着的那一点。余烬本来就不是一簇火，是一点火星。所以新记号的
 *      形状必须是「迸出来的一点」，而不是「一摊正在燃烧的火」。
 *   2. **旧的四个角是对称的几何星。** 对称的四角星今天已经是一个通用的
 *      「AI / 魔法 / 闪光」符号，它不指向这个产品。这个 App 的视觉语言是
 *      手绘的线（底栏四个图标）与像素的块（七个头像），所以新记号也必须是
 *      **一笔一笔画出来的**：四条粗细不同、长度不同、各自弯一点的笔画，
 *      而不是一段参数化生成的完美曲线。
 *
 * ---- 为什么是四条臂，而且长短不一 ----
 *
 * 四条臂让它在 16px 下还是「一个记号」而不是一根线（少于三条臂在通知栏小
 * 图标里会退化成点或斜线）。长短不一是有意的：上长下短 = 往上走，右侧那条
 * 最短 = 被风带了一下。完全对称的四臂星会立刻读成「闪光」，而不对称读成
 * 「刚迸出来、还在动」。
 *
 * ---- 为什么这里全部是纯函数、坐标写死 ----
 *
 * 这个记号要出现在五个地方：App 图标（1024px）、Android 自适应图标
 * （前景/背景/单色）、启动图、通知栏单色图标、落地页顶栏。
 * 它们必须**永远长得一模一样**。所以 path 只在 `SPARK_PATH` 处出现一次，
 * 由 `scripts/make-logo.ts` 一处生成所有 PNG，界面与站点各自引用同一串坐标。
 * 如果每个地方各画一次，改一次形状就要改五处，而且必然有一处忘了改。
 *
 * 坐标约定：24×24 画框。记号本体落在 5.2–18.6 × 2.2–17.8 这一块里
 * （即画框的 65%），四周留白是给图标背景与底栏那种「图形 + 文字」并排用的。
 * 只用绝对命令（M / C / Z）——与 `components/TabBarIcon.tsx` 同一条规矩，
 * 这样 `scripts/svg-raster.ts` 的点阵验形工具也能读它。
 */


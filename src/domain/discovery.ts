/**
 * 今天的那一条发现。
 *
 * 种子是「玩家 id + 业务日」，所以：
 *   - 同一天无论重开几次 App，都是同一条；
 *   - 第二天自动换一条；
 *   - 换设备之后，同一个玩家在同一天拿到的还是同一条（种子不含设备信息）。
 *
 * stream 用 'discovery'：与文案流、动画流分开，多抽一次不会让别的东西变。
 *
 * 返回 null 只在 DISCOVERIES 为空时（正常不会），调用方据此不画那一块。
 */
export function discoveryOfDay(playerId: string, dateKey: string): Discovery | null {
  return pickBySeed(DISCOVERIES, `${playerId}|${dateKey}`, 'discovery') ?? null;
}

/**
 * 今天该不该出现发现。
 *
 * 规则只有一条：**今天至少记过一件**。
 *
 * 为什么不在打开 App 时就给：那会让它变成「每天的问候语」，
 * 而这一条的价值在于「你做完了一件事，顺手看一眼」。顺序反了，
 * 它就从「发现的奖励」变成了「开场白」。
 */
export function shouldShowDiscovery(checkedInToday: boolean): boolean {
  return checkedInToday;
}

/**
 * 今日发现（阶段 4 第 7 条）。
 *
 * ---- 它是什么 ----
 *
 * 每天第一次打卡之后，出现一条「今天发现」。种子化随机：同一天结果固定，
 * 第二天换一条。它是这个 App 里唯一一个**可变奖励**，而可变奖励
 * 只用于探索，不用于消费（D5 的立场）。
 *
 * ---- 为什么它不算「奖励」----
 *
 * 它不给 XP、不给余烬、不给材料。它只是一句话——一条小观察、一个
 * 没想过的角度、一件可以顺手试试的小事。
 *
 * 为什么不做成「随机抽 10 余烬」那种：那会让用户为了刷奖励而打卡，
 * 而打卡的动机一旦变成「抽奖」，它就与习惯养成背道而驰了。
 * 一条文字发现是纯信息，它不改变任何数值，所以也不会被刷。
 *
 * ---- 为什么改系统时间刷不出来 ----
 *
 * 种子是「玩家 id + 业务日」。业务日由 `effectiveToday` 给出，
 * 而它**挡住时钟回拨**（业务日只能前进）。所以把手机时间调回昨天，
 * 拿到的是昨天那条——不是一条新的。
 * 把时间往未来调：业务日会真的前进（我们没法阻止用户这么做），
 * 但那样他跳过的那些天就再也不会有记录——**代价大于收益**，
 * 而这一条并不值得为它加一套防作弊（防作弊本身会带来误伤）。
 *
 * ---- 内容从哪来 ----
 *
 * 手写的常量，40 条（docs/05 阶段 5 说「先 40 条，验证结构后再扩到 200」）。
 * 这一版先做 40 条，每一条都过禁用词表。
 *
 * 本文件是纯函数：不碰数据库、不读系统时间（nowMs 从参数进来）。
 */
import { pickBySeed } from './prng';

/**
 * 发现的种类。
 *
 * 四种，因为它们是四种不同的语气：
 *   - observe  一条观察（「你今天记的时间比平时早」这类）
 *   - idea     一个可以试试的小事
 *   - fact     一条事实（关于习惯、关于记录）
 *   - gentle   一句允许（「今天做到这儿也可以」）
 *
 * 分类不是为了展示（界面上不显示种类），而是为了将来能按种类加权：
 * 全是「可以试试」会变成建议，全是「允许」会变得没有信息量。
 */
export type DiscoveryKind = 'observe' | 'idea' | 'fact' | 'gentle';

/** 一条发现 */
export interface Discovery {
  id: string;
  kind: DiscoveryKind;
  text: string;
}

